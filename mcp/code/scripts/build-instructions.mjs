// Compile ai/lfb_mcp.md (the MCP playbook — pm/mcp.mdx §9) into src/instructions.ts, which the server hands
// to Claude Code as its `instructions`. Build-time, not runtime: the bundled dist/index.js is spawned from an
// arbitrary working directory and must not depend on finding a sibling file on disk.
//
// {VARIABLE} tokens are substituted from the map below. An unknown token FAILS the build — a typo in the
// playbook must not ship to the model as a literal "{EXPORT_DIR}".
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(here, "../../../ai/lfb_mcp.md");
const out = path.resolve(here, "../src/instructions.ts");

const VARS = {
  API_BASE: "http://127.0.0.1:8787/api",
  CREDENTIALS_FILE: "~/.credentials/large_files_bridge.json",
  EXPORTS_DIR: "~/T/_large_files_bridge/fingerprints/exports",
  ERROR_LOG: "~/T/_large_files_bridge/error.err",
};

let text;
try {
  text = fs.readFileSync(src, "utf8");
} catch (e) {
  console.error(`build-instructions: cannot read ${src}: ${e.message}`);
  process.exit(1);
}
const unknown = new Set();
text = text.replace(/\{([A-Z][A-Z0-9_]*)\}/g, (m, name) => {
  if (name in VARS) return VARS[name];
  unknown.add(name);
  return m;
});
if (unknown.size) {
  console.error(`build-instructions: unknown variable(s) in ${src}: ${[...unknown].join(", ")}`);
  process.exit(1);
}
if (text.trim().length < 200) {
  console.error(`build-instructions: ${src} is suspiciously short — refusing to ship empty instructions`);
  process.exit(1);
}
const body =
  "// GENERATED by scripts/build-instructions.mjs from ai/lfb_mcp.md — do not edit; edit the .md and rebuild.\n" +
  "export const INSTRUCTIONS: string = [\n" +
  text.replace(/\s+$/, "").split("\n").map((l) => "  " + JSON.stringify(l)).join(",\n") +
  ',\n].join("\\n");\n';
fs.writeFileSync(out, body);
console.error(`build-instructions: wrote ${path.relative(process.cwd(), out)} (${text.length} chars)`);
